def parse_recipe(text: str) -> list[tuple[str, float]]:
    items: list[tuple[str, float]] = []
    for part in str(text).split("、"):
        match = re.match(r"(.+?)\s*(\d+(?:\.\d+)?)\s*克", part.strip())
        if not match:
            raise ValueError(f"無法解析食材：{part}")
        items.append((match.group(1).strip(), float(match.group(2))))
    return items


def totals(text: str) -> list[float]:
    sums = [0.0] * len(HEADERS)
    for name, grams in parse_recipe(text):
        if name not in N:
            raise KeyError(name)
        factor = grams / 100.0
        for index, raw in enumerate(N[name]):
            sums[index] += raw * factor * TO_G[index]
    return [round(value, DIGITS[index]) for index, value in enumerate(sums)]


